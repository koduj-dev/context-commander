#!/bin/sh
# Dedicated unprivileged user, an owned data dir, a locked-down (empty) env
# file, and the enabled service. Idempotent and safe on both install and
# upgrade (it restarts into the freshly-installed binary). Runs as root from
# dpkg/rpm.
set -e

if ! getent passwd ccd >/dev/null 2>&1; then
	useradd --system --no-create-home --shell /usr/sbin/nologin ccd
fi

install -d -o ccd -g ccd -m 0750 /var/lib/ccd
install -d -m 0755 /etc/context-commander

# CC_ROOT_KEY encrypts everything ccd stores — see internal/crypto/rootkey.go
# and docs/adr/0011-encryption-classification.md. It cannot be generated here:
# there is no safe default, and losing a silently-autogenerated key would
# make already-written data permanently unreadable. The env file is created
# empty (root-only until the operator fills it in) rather than left missing,
# so a fresh install fails loudly instead of falling back to something unsafe.
if [ ! -f /etc/context-commander/ccd.env ]; then
	touch /etc/context-commander/ccd.env
	cat >&2 <<-'EOF'
	ccd: /etc/context-commander/ccd.env created empty. Before the service can
	start, set:
	  CC_DATABASE_URL=postgres://cc_app:...@host:5432/context_commander
	  CC_STORAGE_DIR=/var/lib/ccd/objects
	  CC_ROOT_KEY=$(openssl rand -base64 32)
	then: sudo systemctl start ccd
	EOF
fi
chown root:ccd /etc/context-commander/ccd.env
chmod 0640 /etc/context-commander/ccd.env

if [ -d /run/systemd/system ]; then
	systemctl daemon-reload || true
	systemctl enable ccd.service || true
	# `restart` (not `start`) so an upgrade actually runs the new binary; on a
	# fresh install it just starts it. Harmless if CC_ROOT_KEY/CC_DATABASE_URL
	# aren't set yet — start it later with `systemctl start ccd`.
	systemctl restart ccd.service || true
fi

exit 0
